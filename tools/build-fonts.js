// Embeds the map fonts as base64 so exported SVG/PNG files keep their lettering
// everywhere (also when the page is opened from disk). Run: node tools/build-fonts.js
const fs = require('fs');
const path = require('path');

const root = path.join(__dirname, '..');
const faces = [
  { family: 'Carto Fell', style: 'normal', file: 'fell.woff2' },
  { family: 'Carto Fell', style: 'italic', file: 'fell-italic.woff2' },
  { family: 'Carto Fell SC', style: 'normal', file: 'fell-sc.woff2' },
];

const css = faces.map((f) => {
  const b64 = fs.readFileSync(path.join(root, 'fonts', f.file)).toString('base64');
  return `@font-face{font-family:'${f.family}';font-style:${f.style};font-weight:400;font-display:swap;` +
    `src:url(data:font/woff2;base64,${b64}) format('woff2');}`;
}).join('\n');

const out = `/* Generated by tools/build-fonts.js from fonts/*.woff2 (IM FELL English, SIL OFL 1.1). Do not edit. */
(function (Carto) {
  'use strict';
  Carto.FONT_CSS = ${JSON.stringify(css)};
  if (typeof document !== 'undefined' && document.head) {
    const style = document.createElement('style');
    style.id = 'carto-fonts';
    style.textContent = Carto.FONT_CSS;
    document.head.appendChild(style);
  }
})(window.Carto = window.Carto || {});
`;
fs.writeFileSync(path.join(root, 'js', 'core', 'fonts.js'), out);
console.log('fonts.js written,', Math.round(out.length / 1024), 'KB');
