// Writes sw.js with the list of files to keep offline and a version derived
// from their contents. Run after changing any file: node tools/build-sw.js
const fs = require('fs');
const path = require('path');
const crypto = require('crypto');

const root = path.join(__dirname, '..');
const html = fs.readFileSync(path.join(root, 'index.html'), 'utf8');
const files = ['./', 'index.html', 'manifest.webmanifest', 'css/style.css',
  'icons/favicon.svg', 'icons/icon-192.png', 'icons/icon-512.png', 'icons/apple-touch-icon.png', 'icons/icon-maskable-512.png']
  .concat([...html.matchAll(/<script src="([^"]+)"/g)].map((m) => m[1]));
const hash = crypto.createHash('sha256');
for (const f of files) if (f !== './') hash.update(fs.readFileSync(path.join(root, f)));
const version = hash.digest('hex').slice(0, 12);

const sw = `/* Generated by tools/build-sw.js. Do not edit by hand. */
const VERSION = 'cartografo-${version}';
const FILES = ${JSON.stringify(files, null, 2)};

self.addEventListener('install', (event) => {
  event.waitUntil(caches.open(VERSION).then((cache) => cache.addAll(FILES)).then(() => self.skipWaiting()));
});

self.addEventListener('activate', (event) => {
  event.waitUntil(
    caches.keys()
      .then((keys) => Promise.all(keys.filter((k) => k.startsWith('cartografo-') && k !== VERSION).map((k) => caches.delete(k))))
      .then(() => self.clients.claim())
  );
});

self.addEventListener('fetch', (event) => {
  const req = event.request;
  if (req.method !== 'GET') return;
  const url = new URL(req.url);
  // Never cache the sync service: saves must always be live.
  if (url.hostname.endsWith('supabase.co')) return;
  const sameOrigin = url.origin === self.location.origin;
  const fonts = url.hostname === 'fonts.googleapis.com' || url.hostname === 'fonts.gstatic.com';
  const library = url.hostname === 'cdn.jsdelivr.net';
  if (!sameOrigin && !fonts && !library) return;
  // Cache first, refresh in the background: instant start, works offline.
  event.respondWith(
    caches.open(VERSION).then(async (cache) => {
      const key = req.mode === 'navigate' ? './' : req;
      const hit = await cache.match(key, { ignoreSearch: sameOrigin });
      const fresh = fetch(req).then((res) => {
        if (res && (res.ok || res.type === 'opaque')) cache.put(key, res.clone());
        return res;
      }).catch(() => hit);
      return hit || fresh;
    })
  );
});
`;
fs.writeFileSync(path.join(root, 'sw.js'), sw);
console.log('sw.js written, version', version, '-', files.length, 'files');
